export type Lang = 'zh' | 'en'

export function createT(lang: Lang = 'zh'): (key: string) => string {
  const dict = lang === 'zh' ? zh : en
  return (key: string) => dict[key] ?? key
}

/** 中英双语 section 标题：中文主 + 英文副。 */
export function sectionTitle(t: (k: string) => string, key: string): string {
  return `${t(key)} ${t(key) === en[key] ? '' : '· ' + en[key]}`.trim()
}

export const DEFAULT_T = createT('zh')
export const EN_T = createT('en')
